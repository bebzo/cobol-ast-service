def calculate_kpi(ws_total_assets, ws_net_income, ws_total_equity, ws_interest_expense, ws_earning_assets, ws_total_trans_count, ws_error_count, ws_total_cases, ws_within_sla_count, ws_fcr_count, ws_total_calls, ws_active_customers, ws_churned_customers, ws_marketing_spend, ws_new_customers, ws_avg_revenue_per_customer, ws_avg_customer_tenure) -> None:
    """Calculates KPIs."""
    logger.info("Running calculate_kpi")
    calc_financial_kpi(ws_total_assets, ws_net_income, ws_total_equity, ws_interest_expense, ws_earning_assets)
    calc_operational_kpi(ws_total_trans_count, ws_error_count, ws_total_cases, ws_within_sla_count, ws_fcr_count, ws_total_calls)
    calc_customer_kpi(ws_active_customers, ws_churned_customers, ws_marketing_spend, ws_new_customers, ws_avg_revenue_per_customer, ws_avg_customer_tenure)

def calc_financial_kpi(ws_total_assets, ws_net_income, ws_total_equity, ws_interest_expense, ws_earning_assets) -> None:
    """Calculates financial KPIs."""
    logger.info("Running calc_financial_kpi")
    if ws_total_assets > 0: ws_roa = (ws_net_income / ws_total_assets) * 100
    if ws_total_equity > 0: ws_roe = (ws_net_income / ws_total_equity) * 100
    if ws_interest_expense > 0: ws_nim = ((ws_interest_income - ws_interest_expense) / ws_earning_assets) * 100

def calc_operational_kpi(ws_total_trans_count, ws_error_count, ws_total_cases, ws_within_sla_count, ws_fcr_count, ws_total_calls) -> None:
    """Calculates operational KPIs."""
    logger.info("Running calc_operational_kpi")
    if ws_total_trans_count > 0: ws_error_rate = (ws_error_count / ws_total_trans_count) * 100
    ws_sla_compliance = (ws_within_sla_count / ws_total_cases) * 100
    ws_first_call_resolution = (ws_fcr_count / ws_total_calls) * 100

def calc_customer_kpi(ws_active_customers, ws_churned_customers, ws_marketing_spend, ws_new_customers, ws_avg_revenue_per_customer, ws_avg_customer_tenure) -> None:
    """Calculates customer KPIs."""
    logger.info("Running calc_customer_kpi")
    if ws_active_customers > 0: ws_churn_rate = (ws_churned_customers / ws_active_customers) * 100
    ws_acquisition_cost = ws_marketing_spend / ws_new_customers
    ws_lifetime_value = ws_avg_revenue_per_customer * ws_avg_customer_tenure

