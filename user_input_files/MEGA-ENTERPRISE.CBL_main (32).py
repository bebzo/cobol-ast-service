    ofac_search_bank = ws_beneficiary_bank
    ofacsrch(ofac_request, ofac_response)
    if ofac_match_found == 'Y':
        if ofac_match_score >= 85:
            ws_ofac_clear = 'N'
            ws_wire_reject = 'BANK OFAC MATCH'
    pass

