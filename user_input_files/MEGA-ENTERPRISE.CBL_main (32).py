def check_luhn() -> None:
    """Checks the Luhn algorithm validity of a card number."""
    logger.info("Executing check_luhn")
    ws_luhn_sum = 0;
    ws_luhn_idx = 16
    while ws_luhn_idx >= 1:
        ws_luhn_digit = int(ws_auth_card_number[ws_luhn_idx -1]);
        if (17 - ws_luhn_idx) % 2 == 0:
            ws_luhn_digit *= 2;
            if ws_luhn_digit > 9:
                ws_luhn_digit -= 9
        ws_luhn_sum += ws_luhn_digit
        ws_luhn_idx -= 1
    if ws_luhn_sum % 10 == 0:
        ws_luhn_valid = 'Y'
    else:
        ws_luhn_valid = 'N'

