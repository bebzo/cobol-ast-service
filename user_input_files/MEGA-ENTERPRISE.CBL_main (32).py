def validate_wire_request(ws_wire_amount, ws_account_balance, ws_beneficiary_account, ws_ctr_required) -> None:
    """Validates a wire transfer request."""
    logger.info("Validating wire request")
    ws_wire_valid = 'Y'
    ws_wire_reject = ""
    if ws_wire_amount <= 0:
        ws_wire_valid = 'N'
        ws_wire_reject = 'INVALID AMOUNT'
    if ws_wire_amount > ws_account_balance:
        ws_wire_valid = 'N'
        ws_wire_reject = 'INSUFFICIENT FUNDS'
    if ws_beneficiary_account == " " * len(ws_beneficiary_account):
        ws_wire_valid = 'N'
        ws_wire_reject = 'BENEFICIARY REQUIRED'
    if ws_wire_amount > 10000:
        ws_ctr_required = 'Y'
    pass

