def process_transactions() -> None:
    """Process transactions."""
    logger.info("Starting process_transactions")
    global ws_eof_flag, ws_transaction_rec, ws_counters
    ws_transaction_rec = WsTransactionRec()
    ws_eof_flag = 'Y'
