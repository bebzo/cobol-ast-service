def create_amortization_C7(ws_loan_amount: Decimal, ws_loan_term_months: int, ws_monthly_rate: Decimal, ws_loan_monthly_pmt: Decimal, ws_property_tax: Decimal, ws_insurance_premium: Decimal, ws_pmi_amount: Decimal, loan_mortgage: bool) -> tuple[List[Decimal], List[Decimal], List[Decimal], List[int], List[Decimal], List[Decimal], List[Decimal]]:
    """Creates amortization schedule."""
    amort_interest: List[Decimal] = []
    amort_principal: List[Decimal] = []
    amort_balance: List[Decimal] = []
    amort_payment_num: List[int] = []
    amort_payment_amt: List[Decimal] = []
    amort_escrow: List[Decimal] = []
    amort_total_pmt: List[Decimal] = []

    import datetime
    ws_running_balance = ws_loan_amount
    ws_payment_date = datetime.date.today()
    ws_payment_month = ws_payment_date.month
    ws_payment_year = ws_payment_date.year

    for ws_amort_idx in range(1, ws_loan_term_months + 1):
        interest, principal, balance, payment_num, payment_amt, escrow, total_pmt = calculate_payment_split_C7(
            ws_running_balance, ws_monthly_rate, ws_loan_monthly_pmt, ws_property_tax, ws_insurance_premium, ws_pmi_amount, loan_mortgage, ws_amort_idx, ws_payment_month, ws_payment_year
        )
        amort_interest.append(interest)
        amort_principal.append(principal)
        amort_balance.append(balance)
        amort_payment_num.append(payment_num)
        amort_payment_amt.append(payment_amt)
        amort_escrow.append(escrow)
        amort_total_pmt.append(total_pmt)

        ws_payment_month, ws_payment_year = advance_payment_date_C7(ws_payment_month, ws_payment_year)

    return amort_interest, amort_principal, amort_balance, amort_payment_num, amort_payment_amt, amort_escrow, amort_total_pmt

def calculate_payment_split_C7(ws_running_balance: Decimal, ws_monthly_rate: Decimal, ws_loan_monthly_pmt: Decimal, ws_property_tax: Decimal, ws_insurance_premium: Decimal, ws_pmi_amount: Decimal, loan_mortgage: bool, ws_amort_idx: int, ws_payment_month: int, ws_payment_year: int) -> tuple[Decimal, Decimal, Decimal, int, Decimal, Decimal, Decimal]:
    """Calculates payment split for amortization."""
    amort_interest = ws_running_balance * ws_monthly_rate
    amort_principal = ws_loan_monthly_pmt - amort_interest
    ws_running_balance -= amort_principal
    amort_balance = ws_running_balance
    amort_payment_num = ws_amort_idx
    amort_payment_amt = ws_loan_monthly_pmt

    if loan_mortgage:
        amort_escrow = (ws_property_tax + ws_insurance_premium) / 12
        amort_total_pmt = ws_loan_monthly_pmt + amort_escrow + ws_pmi_amount
    else:
        amort_escrow = Decimal("0.00")
        amort_total_pmt = ws_loan_monthly_pmt

    return amort_interest, amort_principal, amort_balance, amort_payment_num, amort_payment_amt, amort_escrow, amort_total_pmt

