def create_amortization_C7(ws_loan_amount: Decimal, ws_loan_term_months: int, ws_monthly_rate: Decimal, ws_loan_monthly_pmt: Decimal, loan_mortgage: bool, ws_property_tax: Decimal, ws_insurance_premium: Decimal, ws_pmi_amount: Decimal) -> tuple[List[Decimal], List[Decimal], List[Decimal], List[int], List[Decimal], List[Decimal], List[Decimal], List[int], int, int]:
    """Creates amortization schedule."""
    amort_interest: List[Decimal] = [Decimal('0.00')] * (ws_loan_term_months + 1)
    amort_principal: List[Decimal] = [Decimal('0.00')] * (ws_loan_term_months + 1)
    amort_balance: List[Decimal] = [Decimal('0.00')] * (ws_loan_term_months + 1)
    amort_payment_num: List[int] = [0] * (ws_loan_term_months + 1)
    amort_payment_amt: List[Decimal] = [Decimal('0.00')] * (ws_loan_term_months + 1)
    amort_escrow: List[Decimal] = [Decimal('0.00')] * (ws_loan_term_months + 1)
    amort_total_pmt: List[Decimal] = [Decimal('0.00')] * (ws_loan_term_months + 1)
    amort_payment_date: List[int] = [0] * (ws_loan_term_months + 1)
    import datetime
    today = datetime.date.today()
    ws_payment_month = today.month
    ws_payment_year = today.year
    ws_running_balance = ws_loan_amount
    for ws_amort_idx in range(1, ws_loan_term_months + 1):
        amort_interest[ws_amort_idx] = ws_running_balance * ws_monthly_rate
        amort_principal[ws_amort_idx] = ws_loan_monthly_pmt - amort_interest[ws_amort_idx]
        ws_running_balance -= amort_principal[ws_amort_idx]
        amort_balance[ws_amort_idx] = ws_running_balance
        amort_payment_num[ws_amort_idx] = ws_amort_idx
        amort_payment_amt[ws_amort_idx] = ws_loan_monthly_pmt
        if loan_mortgage:
            amort_escrow[ws_amort_idx] = (ws_property_tax + ws_insurance_premium) / 12
            amort_total_pmt[ws_amort_idx] = ws_loan_monthly_pmt + amort_escrow[ws_amort_idx] + ws_pmi_amount
        else:
            amort_total_pmt[ws_amort_idx] = ws_loan_monthly_pmt
        ws_payment_month += 1
        if ws_payment_month > 12:
            ws_payment_month = 1
            ws_payment_year += 1
        amort_payment_date[ws_amort_idx] = ws_payment_year * 10000 + ws_payment_month * 100 + 1
    return amort_interest, amort_principal, amort_balance, amort_payment_num, amort_payment_amt, amort_escrow, amort_total_pmt, amort_payment_date, ws_payment_month, ws_payment_year

