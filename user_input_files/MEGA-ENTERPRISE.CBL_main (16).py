def generate_loan_terms_C7(ws_approved_rate: Decimal, ws_loan_term_months: int, ws_loan_amount: Decimal) -> tuple[Decimal, Decimal, Decimal, Decimal, Decimal]:
    """Generates loan terms."""
    ws_loan_interest_rate: Decimal = ws_approved_rate
    ws_monthly_rate: Decimal = ws_loan_interest_rate / 1200
    ws_compound_factor: Decimal = (1 + ws_monthly_rate) ** ws_loan_term_months
    ws_loan_monthly_pmt: Decimal = ws_loan_amount * ws_monthly_rate * ws_compound_factor / (ws_compound_factor - 1)
    ws_loan_principal_bal: Decimal = ws_loan_amount
    return ws_loan_interest_rate, ws_monthly_rate, ws_compound_factor, ws_loan_monthly_pmt, ws_loan_principal_bal

def create_amortization_C7(ws_loan_amount: Decimal, ws_loan_term_months: int, ws_monthly_rate: Decimal, ws_loan_monthly_pmt: Decimal, loan_mortgage: bool, ws_property_tax: Decimal, ws_insurance_premium: Decimal, ws_pmi_amount: Decimal) -> tuple[List[Decimal], List[Decimal], List[Decimal], List[int], List[Decimal], List[Decimal], List[Decimal]]:
    """Creates an amortization schedule."""
    ws_running_balance: Decimal = ws_loan_amount
    import datetime
    today = datetime.date.today()
    ws_payment_year: int = today.year
    ws_payment_month: int = today.month
    ws_payment_date = today
    amort_interest: List[Decimal] = [Decimal("0.00")] * (ws_loan_term_months + 1)
    amort_principal: List[Decimal] = [Decimal("0.00")] * (ws_loan_term_months + 1)
    amort_balance: List[Decimal] = [Decimal("0.00")] * (ws_loan_term_months + 1)
    amort_payment_num: List[int] = [0] * (ws_loan_term_months + 1)
    amort_payment_amt: List[Decimal] = [Decimal("0.00")] * (ws_loan_term_months + 1)
    amort_escrow: List[Decimal] = [Decimal("0.00")] * (ws_loan_term_months + 1)
    amort_total_pmt: List[Decimal] = [Decimal("0.00")] * (ws_loan_term_months + 1)

    for ws_amort_idx in range(1, ws_loan_term_months + 1):
        amort_interest[ws_amort_idx], amort_principal[ws_amort_idx], ws_running_balance, amort_balance[ws_amort_idx], amort_payment_num[ws_amort_idx], amort_payment_amt[ws_amort_idx], amort_escrow[ws_amort_idx], amort_total_pmt[ws_amort_idx] = calculate_payment_split_C7(ws_running_balance, ws_monthly_rate, ws_loan_monthly_pmt, loan_mortgage, ws_property_tax, ws_insurance_premium, ws_pmi_amount, ws_amort_idx, ws_payment_month, ws_payment_year)
        ws_payment_month, ws_payment_year = advance_payment_date_C7(ws_payment_month, ws_payment_year, ws_amort_idx)
    return amort_interest, amort_principal, amort_balance, amort_payment_num, amort_payment_amt, amort_escrow, amort_total_pmt

def calculate_payment_split_C7(ws_running_balance: Decimal, ws_monthly_rate: Decimal, ws_loan_monthly_pmt: Decimal, loan_mortgage: bool, ws_property_tax: Decimal, ws_insurance_premium: Decimal, ws_pmi_amount: Decimal, ws_amort_idx: int, ws_payment_month: int, ws_payment_year: int) -> tuple[Decimal, Decimal, Decimal, Decimal, int, Decimal, Decimal, Decimal]:
    """Calculates the payment split between interest and principal."""
    amort_interest = ws_running_balance * ws_monthly_rate
    amort_principal = ws_loan_monthly_pmt - amort_interest
    ws_running_balance -= amort_principal
    amort_balance = ws_running_balance
    amort_payment_num = ws_amort_idx
    amort_payment_amt = ws_loan_monthly_pmt

    if loan_mortgage:
        amort_escrow = (ws_property_tax + ws_insurance_premium) / 12
        amort_total_pmt = ws_loan_monthly_pmt + amort_escrow + ws_pmi_amount
    else:
        amort_escrow = Decimal("0.00")
        amort_total_pmt = ws_loan_monthly_pmt

    return amort_interest, amort_principal, ws_running_balance, amort_balance, amort_payment_num, amort_payment_amt, amort_escrow, amort_total_pmt

