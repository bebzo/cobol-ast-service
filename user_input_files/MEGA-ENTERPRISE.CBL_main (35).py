def check_luhn() -> None:
    """Checks LUHN."""
    logger.info("check_luhn")
    global WS_LUHN_SUM, WS_AUTH_CARD_NUMBER, WS_LUHN_IDX, WS_LUHN_DIGIT, WS_LUHN_VALID
    WS_LUHN_SUM = Decimal("0")
    ws_luhn_idx = 16
    while ws_luhn_idx >= 1:
        ws_luhn_digit = Decimal(WS_AUTH_CARD_NUMBER[ws_luhn_idx-1])
        if (17 - ws_luhn_idx) % 2 == 0:
            ws_luhn_digit *= 2
            if ws_luhn_digit > Decimal("9"):
                ws_luhn_digit -= Decimal("9")
        WS_LUHN_SUM += ws_luhn_digit
        ws_luhn_idx -= 1
    if WS_LUHN_SUM % 10 == 0:
        WS_LUHN_VALID = 'Y'
    else:
        WS_LUHN_VALID = 'N'

