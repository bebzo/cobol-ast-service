def generate_loan_terms_C7(ws_approved_rate: Decimal, ws_loan_term_months: int, ws_loan_amount: Decimal) -> Tuple[Decimal, Decimal, Decimal, Decimal]:
    """Generates loan terms."""
    ws_loan_interest_rate: Decimal = ws_approved_rate
    ws_monthly_rate: Decimal = ws_loan_interest_rate / 1200
    ws_compound_factor: Decimal = (1 + ws_monthly_rate) ** ws_loan_term_months
    ws_loan_monthly_pmt: Decimal = ws_loan_amount * ws_monthly_rate * ws_compound_factor / (ws_compound_factor - 1)
    ws_loan_principal_bal: Decimal = ws_loan_amount
    return ws_loan_interest_rate, ws_monthly_rate, ws_compound_factor, ws_loan_monthly_pmt

def create_amortization_C7(ws_loan_amount: Decimal, ws_loan_term_months: int, ws_monthly_rate: Decimal, ws_loan_monthly_pmt: Decimal, ws_property_tax: Decimal, ws_insurance_premium: Decimal, ws_pmi_amount: Decimal, loan_mortgage: bool) -> Tuple[List[Decimal], List[Decimal], List[Decimal], List[int], List[Decimal], List[Decimal]]:
    """Creates an amortization schedule."""
    ws_running_balance: Decimal = ws_loan_amount
    amort_interest: List[Decimal] = [Decimal(0)] * (ws_loan_term_months + 1)
    amort_principal: List[Decimal] = [Decimal(0)] * (ws_loan_term_months + 1)
    amort_balance: List[Decimal] = [Decimal(0)] * (ws_loan_term_months + 1)
    amort_payment_num: List[int] = [0] * (ws_loan_term_months + 1)
    amort_payment_amt: List[Decimal] = [Decimal(0)] * (ws_loan_term_months + 1)
    amort_escrow: List[Decimal] = [Decimal(0)] * (ws_loan_term_months + 1)
    amort_total_pmt: List[Decimal] = [Decimal(0)] * (ws_loan_term_months + 1)

    import datetime
    today = datetime.date.today()
    ws_payment_year: int = today.year
    ws_payment_month: int = today.month
    
    for ws_amort_idx in range(1, ws_loan_term_months + 1):
        amort_interest[ws_amort_idx], amort_principal[ws_amort_idx], ws_running_balance = calculate_payment_split_C7(ws_running_balance, ws_monthly_rate, ws_loan_monthly_pmt)
        amort_balance[ws_amort_idx] = ws_running_balance
        amort_payment_num[ws_amort_idx] = ws_amort_idx
        amort_payment_amt[ws_amort_idx] = ws_loan_monthly_pmt
        
        if loan_mortgage:
            amort_escrow[ws_amort_idx] = (ws_property_tax + ws_insurance_premium) / 12
            amort_total_pmt[ws_amort_idx] = ws_loan_monthly_pmt + amort_escrow[ws_amort_idx] + ws_pmi_amount
        else:
            amort_total_pmt[ws_amort_idx] = ws_loan_monthly_pmt

        ws_payment_year, ws_payment_month = advance_payment_date_C7(ws_payment_year, ws_payment_month)

    return amort_interest, amort_principal, amort_balance, amort_payment_num, amort_payment_amt, amort_total_pmt

def calculate_payment_split_C7(ws_running_balance: Decimal, ws_monthly_rate: Decimal, ws_loan_monthly_pmt: Decimal) -> Tuple[Decimal, Decimal, Decimal]:
    """Calculates the interest and principal split for a payment."""
    amort_interest: Decimal = ws_running_balance * ws_monthly_rate
    amort_principal: Decimal = ws_loan_monthly_pmt - amort_interest
    ws_running_balance -= amort_principal
    return amort_interest, amort_principal, ws_running_balance

def advance_payment_date_C7(ws_payment_year: int, ws_payment_month: int) -> Tuple[int, int]:
    """Advances the payment date by one month."""
    ws_payment_month += 1
    if ws_payment_month > 12:
        ws_payment_month = 1
        ws_payment_year += 1
    return ws_payment_year, ws_payment_month

