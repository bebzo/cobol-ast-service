import datetime


def calculate_next_run_date_C10(ws_last_run_date: datetime.date, run_frequency: str) -> datetime.date:
    """Calculates the next run date based on the frequency."""
    if run_frequency == 'DAILY':
        ws_next_run_date = ws_last_run_date + datetime.timedelta(days=1)
    elif run_frequency == 'WEEKLY':
        ws_next_run_date = ws_last_run_date + datetime.timedelta(days=7)
    elif run_frequency == 'MONTHLY':
        ws_next_run_date = ws_last_run_date + datetime.timedelta(days=30)
    elif run_frequency == 'QUARTERLY':
        ws_next_run_date = ws_last_run_date + datetime.timedelta(days=90)
    elif run_frequency == 'YEARLY':
        ws_next_run_date = ws_last_run_date + datetime.timedelta(days=365)
    else:
        ws_next_run_date = ws_last_run_date
    return ws_next_run_date

