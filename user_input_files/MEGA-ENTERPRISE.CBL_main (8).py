def create_amortization_C7(ws_loan_amount: Decimal, ws_loan_term_months: int, ws_monthly_rate: Decimal, ws_loan_monthly_pmt: Decimal, ws_property_tax: Decimal, ws_insurance_premium: Decimal, ws_pmi_amount: Decimal, loan_mortgage: bool) -> tuple[List[Decimal], List[Decimal], List[Decimal], List[int], List[Decimal], List[Decimal]]:
    """Creates an amortization schedule."""
    ws_running_balance = ws_loan_amount
