import datetime


def calculate_next_run_date_C10(ws_last_run_date: str, schedule_type: str) -> None:
    """Calculates the next run date."""
    if schedule_type == 'DAILY':
        ws_next_run_date = datetime.datetime.strptime(ws_last_run_date, '%Y%m%d').toordinal() + 1
    elif schedule_type == 'WEEKLY':
        ws_next_run_date = datetime.datetime.strptime(ws_last_run_date, '%Y%m%d').toordinal() + 7
    elif schedule_type == 'MONTHLY':
        ws_next_run_date = datetime.datetime.strptime(ws_last_run_date, '%Y%m%d').toordinal() + 30
    elif schedule_type == 'QUARTERLY':
        ws_next_run_date = datetime.datetime.strptime(ws_last_run_date, '%Y%m%d').toordinal() + 90
    elif schedule_type == 'YEARLY':
        ws_next_run_date = datetime.datetime.strptime(ws_last_run_date, '%Y%m%d').toordinal() + 365
    else:
        ws_next_run_date = None
    return ws_next_run_date

