    """Calculate tax based on brackets."""
    global WS_CALC_TAX
    if WS_CALC_AMOUNT <= WS_BRACKET_1_MAX:
        WS_CALC_TAX = WS_CALC_AMOUNT * WS_BRACKET_1_RATE
    elif WS_CALC_AMOUNT <= WS_BRACKET_2_MAX:
        WS_CALC_TAX = (WS_BRACKET_1_MAX * WS_BRACKET_1_RATE) + \
                      ((WS_CALC_AMOUNT - WS_BRACKET_1_MAX) * WS_BRACKET_2_RATE)
    elif WS_CALC_AMOUNT <= WS_BRACKET_3_MAX:
        WS_CALC_TAX = (WS_BRACKET_1_MAX * WS_BRACKET_1_RATE) + \
                      ((WS_BRACKET_2_MAX - WS_BRACKET_1_MAX) * WS_BRACKET_2_RATE) + \
                      ((WS_CALC_AMOUNT - WS_BRACKET_2_MAX) * WS_BRACKET_3_RATE)
    else:
        WS_CALC_TAX = WS_CALC_AMOUNT * WS_BRACKET_5_RATE

