def calculate_payment_split_C7(ws_running_balance: Decimal, ws_monthly_rate: float, ws_loan_monthly_pmt: Decimal, ws_property_tax: Decimal, ws_insurance_premium: Decimal, ws_pmi_amount: Decimal, loan_mortgage: bool, ws_amort_idx: int) -> Tuple[Decimal, Decimal, Decimal, Decimal, int, Decimal, Decimal, Decimal]:
    """Calculates payment split."""
    amort_interest: Decimal = ws_running_balance * Decimal(str(ws_monthly_rate))
    amort_principal: Decimal = ws_loan_monthly_pmt - amort_interest
    ws_running_balance -= amort_principal
    amort_balance: Decimal = ws_running_balance
    amort_payment_num: int = ws_amort_idx
    amort_payment_amt: Decimal = ws_loan_monthly_pmt
    amort_escrow: Decimal = Decimal('0.00')
    amort_total_pmt: Decimal = Decimal('0.00')
    if loan_mortgage:
        amort_escrow = (ws_property_tax + ws_insurance_premium) / 12
        amort_total_pmt = ws_loan_monthly_pmt + amort_escrow + ws_pmi_amount
    else:
        amort_total_pmt = ws_loan_monthly_pmt
    return amort_interest, amort_principal, ws_running_balance, amort_balance, amort_payment_num, amort_payment_amt, amort_escrow, amort_total_pmt

