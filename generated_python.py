def generate_loan_terms_C7(ws_approved_rate: Decimal, ws_loan_term_months: int, ws_loan_amount: Decimal) -> tuple[Decimal, Decimal, Decimal]:
    """10500-generate_loan_terms
    """
    ws_loan_interest_rate: Decimal = ws_approved_rate
