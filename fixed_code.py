def calculate_luhn_check(ws_card_number_temp: str, ws_luhn_sum: Decimal, ws_luhn_idx: int, ws_luhn_digit: Decimal, ws_luhn_check: Decimal) -> None:
    """Calculate Luhn check."""
    logger.info("Calculating Luhn check")
    ws_luhn_sum = Decimal("0")
    for ws_luhn_idx in range(15, 0, -1):
        ws_luhn_digit = Decimal(ws_card_number_temp[ws_luhn_idx - 1])
        if (16 - ws_luhn_idx) % 2 == 0:
            ws_luhn_digit *= 2
            if ws_luhn_digit > 9:
                ws_luhn_digit -= 9
        ws_luhn_sum += ws_luhn_digit
    ws_luhn_check = Decimal((10 - (ws_luhn_sum % 10)) % 10)

